using System.ComponentModel.DataAnnotations;
using System.Text.Json.Serialization;
using SenicPosSaaS.Domain.Enums;

namespace SenicPosSaaS.Application.DTOs.Order;

public class CreateOrderDto
{
    /// <summary>Set by the API from the signed-in user; never read from the request body.</summary>
    [JsonIgnore]
    public Guid TenantId { get; set; }

    /// <summary>Null for a walk-in customer.</summary>
    public Guid? CustomerId { get; set; }

    public PaymentMethod PaymentMethod { get; set; }

    [Range(0, double.MaxValue)]
    public decimal DiscountAmount { get; set; }

    public string? Notes { get; set; }

    /// <summary>
    /// Optional id generated by the client. Sending the same id again returns the order that
    /// was already created instead of creating a duplicate.
    /// </summary>
    public Guid? ClientOrderId { get; set; }

    [MinLength(1)]
    public List<CreateOrderItemDto> Items { get; set; } = new();
}

public class CreateOrderItemDto
{
    public Guid InventoryItemId { get; set; }

    [Range(1, int.MaxValue)]
    public int Quantity { get; set; }

    [Range(0, double.MaxValue)]
    public decimal Discount { get; set; }
}
